// Scaffold axes (issue #480): the default is one in-job workflow, artifact
// storage, advisory gate. These opt-ins select the architectures tests exercise:
// --storage branch emits the publish-base job, --workflow split emits the
// untrusted-capture + trusted-report pair, --mode review-gate emits the approve
// caller workflow. LEGACY_SCAFFOLD reproduces the pre-#480 file set exactly.
const BRANCH = ['--storage', 'branch'];
const SPLIT = ['--workflow', 'split'];
const REVIEW = ['--mode', 'review-gate'];
const LEGACY_SCAFFOLD = [...SPLIT, ...BRANCH, ...REVIEW];

const runInit = (cwd, args = [], env = {}) => {
  const hasServerChoice = args.some(
    (arg) => arg === '--server-command' || arg.startsWith('--server-command=') || arg === '--external-server',
  );
  const packagePath = path.join(cwd, 'package.json');
  const fixtureArgs =
    !hasServerChoice && !fs.existsSync(packagePath)
      ? [...args, '--server-command', 'npm run build && npm run start']
      : args;
  return spawnSync(process.execPath, [INIT, ...fixtureArgs], {
    cwd,
    encoding: 'utf8',
    env: { ...process.env, ...env },
  });
};
function touch(root, rel) {
  const f = path.join(root, rel);
  fs.mkdirSync(path.dirname(f), { recursive: true });
  fs.writeFileSync(f, '');
}
const readSpec = (root) => fs.readFileSync(path.join(root, 'e2e/styleproof.spec.ts'), 'utf8');
// The shim styleproof-init wrote under --storage branch before 8.0.0.
const GENERATED_HOOK = `#!/bin/sh
# StyleProof pre-push (generated by styleproof-init; refresh with: styleproof-init --hook).
[ "\${STYLEPROOF_SKIP_CAPTURE:-}" = "1" ] && exit 0
exec ./node_modules/.bin/styleproof-prepush
`;
function writeGeneratedHook(root, dir) {
  fs.mkdirSync(path.join(root, dir), { recursive: true });
  fs.writeFileSync(path.join(root, dir, 'pre-push'), GENERATED_HOOK, { mode: 0o755 });
}
const gitConfigGet = (root, key) =>
  spawnSync('git', ['config', '--local', '--get', key], { cwd: root, encoding: 'utf8' }).stdout.trim();
const readFile = (root, rel) => fs.readFileSync(path.join(root, rel), 'utf8');

test('styleproof-init: imports the routes leaf, not the barrel (keeps the heavy capture graph out of the scaffolder)', () => {
  // styleproof-init only writes files; it must not drag capture/crawler/report
  // and their Playwright-importing modules into its load path. That oversized,
  // concurrently-loaded module graph is what flaked init's tests in CI.
  const src = fs.readFileSync(INIT, 'utf8');
  assert.match(src, /from '\.\.\/dist\/routes\.js'/);
  assert.doesNotMatch(src, /from '\.\.\/dist\/index\.js'/);
});

