      assert.match(workflow, /^\s{2}report-sweep:/m);
      assert.match(workflow, /if: github\.event_name == 'schedule'/);
      assert.match(workflow, /--retention-days 14/);
      assert.match(workflow, /--budget-bytes 1500000000/);

