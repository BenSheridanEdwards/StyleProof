// StyleProof runs in CI. Releases before 8.0.0 generated a pre-push hook under
// --storage branch; --check reports it and --upgrade retires it.
import fs from 'node:fs';
import path from 'node:path';
import { spawnSync } from 'node:child_process';
import { generatedPathState, readRegularTextFile } from './files.mjs';

const GENERATED_HEADER = '# StyleProof pre-push (generated by styleproof-init';
// Every command line any release's shim held. A line outside this set is the owner's.
const SHIM_LINES = [
  /^\[ "\$\{STYLEPROOF_SKIP_CAPTURE:-\}" = "1" \] && exit 0$/,
  /^if \[ ! -x \.\/node_modules\/\.bin\/styleproof-prepush \]; then$/,
  /^echo "StyleProof: [^"]*" >&2$/,
  /^exit 0$/,
  /^fi$/,
  /^STYLEPROOF_SPEC_PATH_B64='[A-Za-z0-9+/=]*'$/,
  /^export STYLEPROOF_SPEC_PATH_B64$/,
  /^exec \S.*\bstyleproof-prepush\b.*$/,
];
const isGeneratedShim = (text) =>
  text.includes(GENERATED_HEADER) &&
  text
    .split('\n')
    .map((line) => line.trim())
    .filter((line) => line && !line.startsWith('#'))
    .every((line) => SHIM_LINES.some((shape) => shape.test(line)));
const GITHOOKS_DIR = '.githooks';
const HOOK_FILES = [`${GITHOOKS_DIR}/pre-push`, '.husky/pre-push'];

const git = (args) => spawnSync('git', args, { encoding: 'utf8' });

/** Pre-push hooks that run StyleProof: `generated` ones init may delete, and
 *  `repository-owned` ones whose StyleProof lines the owner removes. */
export function findStyleProofHooks() {
  return HOOK_FILES.flatMap((file) => {
    if (generatedPathState(file).kind !== 'file') return [];
    const text = readRegularTextFile(file);
    if (text === undefined || !/styleproof/i.test(text)) return [];
    return [{ file, kind: isGeneratedShim(text) ? 'generated' : 'repository-owned' }];
  });
}

const ownedGuidance = (file) => `repository-owned ${file} still runs StyleProof; delete the StyleProof lines`;

/** --check: one line per hook; returns how many need --upgrade. */
export function reportObsoleteHooks() {
  let obsolete = 0;
  for (const hook of findStyleProofHooks()) {
    if (hook.kind === 'generated') {
      console.log(`obsolete ${hook.file} (StyleProof runs in CI; --upgrade removes it)`);
      obsolete++;
    } else console.log(ownedGuidance(hook.file));
  }
  return obsolete;
}

/** --upgrade: delete generated hooks; leave repository-owned ones to their owner. */
export function retireObsoleteHooks() {
  for (const hook of findStyleProofHooks()) {
    if (hook.kind === 'repository-owned') {
      console.log(ownedGuidance(hook.file));
      continue;
    }
    fs.rmSync(hook.file);
    console.log(`removed  ${hook.file} (StyleProof runs in CI)`);
    if (hook.file.startsWith(`${GITHOOKS_DIR}/`)) retireGithooksDir();
  }
}

// The generated hook was the only reason init set core.hooksPath=.githooks. Unset it
// only when Git resolves it to this folder, not to a .githooks elsewhere in the repo.
function retireGithooksDir() {
  if (generatedPathState(GITHOOKS_DIR).kind !== 'directory' || fs.readdirSync(GITHOOKS_DIR).length) return;
  const activeHooks = git(['rev-parse', '--git-path', 'hooks']).stdout?.trim();
  fs.rmdirSync(GITHOOKS_DIR);
  console.log(`removed  ${GITHOOKS_DIR}/`);
  if (!activeHooks || path.resolve(activeHooks) !== path.resolve(GITHOOKS_DIR)) return;
  for (const scope of ['--local', '--worktree']) {
    if (git(['config', scope, '--get', 'core.hooksPath']).stdout?.trim() !== GITHOOKS_DIR) continue;
    if (git(['config', scope, '--unset', 'core.hooksPath']).status === 0)
      console.log(`unset    core.hooksPath (${scope.slice(2)} scope)`);
  }
}
